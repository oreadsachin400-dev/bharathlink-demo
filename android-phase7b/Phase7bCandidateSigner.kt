package com.bharathlink.app.phase7

import android.security.keystore.KeyProperties
import android.util.Base64
import org.json.JSONObject
import java.math.BigInteger
import java.nio.charset.StandardCharsets
import java.security.KeyStore
import java.security.MessageDigest
import java.security.PrivateKey
import java.security.Signature
import java.security.interfaces.ECPublicKey

/**
 * SOURCE-ONLY future native adapter. NOT installed, not enabled, no network calls.
 * Must be invoked only after a fresh native GoTrue TEST session check; it
 * cannot grant server trust, approve an account, or register an E2EE device.
 *
 * Uses Phase 7A's disposable signing aliases INSIDE THE SAME PACKAGE only.
 * Never touches Phase 6 or the original KeyPrep application.
 */
internal object Phase7bCandidateSigner {
    private const val SIGN_ALIAS = "bharathlink_phase7a_disposable_sign"
    private const val ECDH_ALIAS = "bharathlink_phase7a_disposable_ecdh"

    private fun keys() = KeyStore.getInstance("AndroidKeyStore")
        .also { it.load(null) }

    private fun p256Public(ks: KeyStore, alias: String): ECPublicKey {
        check(ks.containsAlias(alias)) { "Missing TEST Keystore alias" }
        val key = ks.getCertificate(alias)?.publicKey as? ECPublicKey
            ?: error("Not an EC public key")
        // Both points must have 256-bit field; only aliases generated by this
        // TEST package can be used.
        check(key.params.curve.field.fieldSize == 256)
        return key
    }

    private fun fixed32(x: BigInteger): ByteArray {
        check(x.signum() >= 0)
        val raw = x.toByteArray()
        val off = if (raw.size == 33 && raw[0] == 0.toByte()) 1 else 0
        val len = raw.size - off
        check(len in 1..32)
        return ByteArray(32).also {
            System.arraycopy(raw, off, it, 32-len, len)
        }
    }
    private fun b64(bytes: ByteArray) = Base64.encodeToString(
        bytes, Base64.URL_SAFE or Base64.NO_PADDING or Base64.NO_WRAP)
    private fun publicJwk(pub: ECPublicKey): JSONObject = JSONObject()
        .put("kty","EC").put("crv","P-256")
        .put("x",b64(fixed32(pub.w.affineX)))
        .put("y",b64(fixed32(pub.w.affineY)))

    fun localPublicJwks(): Pair<JSONObject, JSONObject> {
        val ks = keys()
        // Order is ECDH then ECDSA, same as candidate start API.
        return Pair(publicJwk(p256Public(ks,ECDH_ALIAS)),
            publicJwk(p256Public(ks,SIGN_ALIAS)))
    }

    private fun fingerprint(pub:ECPublicKey):String {
        val canonical = listOf("EC","P-256",
            b64(fixed32(pub.w.affineX)),b64(fixed32(pub.w.affineY)))
            .joinToString("\n")
        return MessageDigest.getInstance("SHA-256")
            .digest(canonical.toByteArray(StandardCharsets.UTF_8))
            .joinToString("") { "%02x".format(it.toInt() and 255) }
    }

    fun signProofFromAuthenticatedTestSession(
        serverPayload: String,
        verifiedUserId: String,
        expectedProofId: String,
        localDeviceId: String,
        boundUserId: String?,
        boundSigningFingerprint: String?,
        boundEcdhFingerprint: String?,
        sessionValidInForeground: Boolean,
        nowMs: Long=System.currentTimeMillis()
    ): String {
        check(sessionValidInForeground) { "Verified foreground session required" }
        check(boundUserId == verifiedUserId &&
            boundSigningFingerprint != null && boundEcdhFingerprint != null)
        check(Phase7bChallengePolicy.accepts(
            serverPayload,verifiedUserId,localDeviceId,expectedProofId,nowMs))
        val ks = keys()
        val signing = p256Public(ks,SIGN_ALIAS)
        val ecdh = p256Public(ks,ECDH_ALIAS)
        check(fingerprint(signing) == boundSigningFingerprint &&
            fingerprint(ecdh) == boundEcdhFingerprint)
        val privateKey = ks.getKey(SIGN_ALIAS,null) as? PrivateKey
            ?: error("Missing non-exportable TEST signing key")
        val der = Signature.getInstance("SHA256withECDSA").run {
            initSign(privateKey)
            update(serverPayload.toByteArray(StandardCharsets.UTF_8))
            sign()
        }
        // The Edge function accepts strict DER ECDSA P-256 base64url.
        return b64(der)
    }
}
