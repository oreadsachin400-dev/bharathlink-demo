/**
 * OFFLINE, DISPOSABLE security diagnostics. A NEW Android package with its own
 * Keystore sandbox, no INTERNET permission, no Supabase credentials or login.
 *
 * Nothing here can approve a device or migrate pre-existing KeyPrep keys.
 * This test does not prove hardware-backed execution or identity verification.
 */
class FreshKeyPrepActivity : Activity() {
    companion object {
        private const val PREFS = "freshprep_offline_v1"
        private const val DEVICE_ID = "test_device_id"
        private const val SIGN_ALIAS = "bharathlink_freshprep_v1_sign"
        private const val ECDH_ALIAS = "bharathlink_freshprep_v1_ecdh"
    }

    private lateinit var result: TextView

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        val content = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            setPadding(32, 34, 32, 34)
        }
        fun info(value: String, size: Float): TextView {
            return TextView(this).also {
                it.text = value
                it.textSize = size
                it.setTextIsSelectable(true)
                it.setPadding(0, 13, 0, 13)
                content.addView(it)
            }
        }
        info("BharathLink — FRESH KEY PREP TEST", 23f)
        info(
            "ISOLATED / OFFLINE / TEST ONLY. Generates NEW disposable P-256 keys " +
            "inside THIS app's AndroidKeyStore after you press Create. " +
            "Does not read, reset, update or migrate original KeyPrep.",
            15f
        )
        info(
            "NO ACCOUNT LOGIN • NO INTERNET • NO ENROLLMENT • NO KYC • NO E2EE ACTIVATION",
            14f
        )
        content.addView(Button(this).apply {
            text = "1. CREATE DISPOSABLE TEST KEYS"
            setOnClickListener { createOnce() }
        })
        content.addView(Button(this).apply {
            text = "2. RUN LOCAL CRYPTO SELF-TEST"
            setOnClickListener { selfTest() }
        })
        content.addView(Button(this).apply {
            text = "3. CHECK LOCAL STATUS"
            setOnClickListener { result.text = currentStatus() }
        })
        result = info(currentStatus(), 15f)
        info(
            "A PASS means only this app's LOCAL P-256 ECDSA and ECDH self-tests work. " +
            "It is NOT a server challenge, independent identity proof, trusted device, " +
            "message decryption or two-phone test. Do not install over original KeyPrep.",
            13f
        )
        val scroll = ScrollView(this)
        scroll.addView(content, ViewGroup.LayoutParams(-1, -2))
        setContentView(scroll)
    }

    private fun store(): KeyStore =
        KeyStore.getInstance("AndroidKeyStore").also { it.load(null) }

    private fun savedId(): String? =
        getSharedPreferences(PREFS, MODE_PRIVATE).getString(DEVICE_ID, null)

    private fun currentStatus(): String {
        return try {
            val ks = store()
            val sign = ks.containsAlias(SIGN_ALIAS)
            val ecdh = ks.containsAlias(ECDH_ALIAS)
            val id = savedId()
            when {
                !sign && !ecdh && id == null ->
                    "NOT_STARTED. No keys generated by this TEST app."
                sign && ecdh && id != null &&
                    OfflineProofPolicy.canonicalPayload(
                        id, "22222222-2222-4222-8222-222222222222",
                        1000L, 2000L, "a".repeat(64), "b".repeat(64)
                    ) != null ->
                    "LOCAL_KEYS_ONLY_NOT_VERIFIED\n" +
                    "Test device ID: $id\n" +
                    "Signing key: present (this package only)\n" +
                    "ECDH key: present (this package only)\n" +
                    "serverApproved: false\ntrustedDevice: false\ne2eeV2Ready: false"
                else -> "PARTIAL_OR_INVALID_LOCAL_KEYS — BLOCKED. " +
                    "No automatic key replacement or account enrollment."
            }
        } catch (_: Exception) {
            "LOCAL_KEY_STATUS_UNAVAILABLE — BLOCKED. No keys modified."
        }
    }

    private fun keyGenerator(alias: String, purposes: Int): KeyPairGenerator {
        val spec = KeyGenParameterSpec.Builder(alias, purposes)
            .setAlgorithmParameterSpec(ECGenParameterSpec("secp256r1"))
        if (purposes and KeyProperties.PURPOSE_SIGN != 0) {
            spec.setDigests(KeyProperties.DIGEST_SHA256)
        }
        return KeyPairGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_EC, "AndroidKeyStore"
        ).also { it.initialize(spec.build()) }
    }

    private fun createOnce() {
        result.text = try {
            val ks = store()
            if (ks.containsAlias(SIGN_ALIAS) ||
                ks.containsAlias(ECDH_ALIAS) || savedId() != null) {
                currentStatus() + "\nGeneration refused: keys/state already exist."
            } else {
                // User must deliberately tap; no generate-on-launch.
                keyGenerator(SIGN_ALIAS,
                    KeyProperties.PURPOSE_SIGN or KeyProperties.PURPOSE_VERIFY
                ).generateKeyPair()
                keyGenerator(ECDH_ALIAS, KeyProperties.PURPOSE_AGREE_KEY
                ).generateKeyPair()
                val newId = UUID.randomUUID().toString()
                check(getSharedPreferences(PREFS, MODE_PRIVATE)
                    .edit().putString(DEVICE_ID, newId).commit())
                currentStatus() +
                    "\nDISPOSABLE TEST KEYS CREATED. Now run local self-test."
            }
        } catch (_: Exception) {
            "KEY_GENERATION_FAILED_OR_PARTIAL — BLOCKED. " +
                "No automatic retry or deletion. Existing KeyPrep is untouched."
        }
    }

    private fun fixed32(n: BigInteger): ByteArray {
        require(n.signum() >= 0)
        val raw = n.toByteArray()
        val offset = if (raw.size == 33 && raw[0] == 0.toByte()) 1 else 0
        val length = raw.size - offset
        require(length in 1..32)
        return ByteArray(32).also {
            System.arraycopy(raw, offset, it, 32 - length, length)
        }
    }

    private fun fingerprint(pub: ECPublicKey): String {
        fun component(n: BigInteger): String =
            Base64.encodeToString(
                fixed32(n),
                Base64.URL_SAFE or Base64.NO_PADDING or Base64.NO_WRAP
            )
        val canonical = listOf(
            "EC", "P-256",
            component(pub.w.affineX), component(pub.w.affineY)
        ).joinToString("\n")
        return MessageDigest.getInstance("SHA-256")
            .digest(canonical.toByteArray(StandardCharsets.UTF_8))
            .joinToString("") { "%02x".format(it.toInt() and 255) }
    }

    private fun runECDH(ownPrivate: PrivateKey, ownPublic: ECPublicKey): Boolean {
        // Ephemeral other party exists only in memory; this is NOT another phone.
        val peer = KeyPairGenerator.getInstance("EC").apply {
            initialize(ECGenParameterSpec("secp256r1"))
        }.generateKeyPair()
        val sharedFromKeyStore = KeyAgreement.getInstance("ECDH").run {
            init(ownPrivate)
            doPhase(peer.public, true)
            generateSecret()
        }
        val sharedFromPeer = KeyAgreement.getInstance("ECDH").run {
            init(peer.private)
            doPhase(ownPublic, true)
            generateSecret()
        }
        return try {
            sharedFromKeyStore.size >= 32 &&
                MessageDigest.isEqual(sharedFromKeyStore, sharedFromPeer)
        } finally {
            sharedFromKeyStore.fill(0)
            sharedFromPeer.fill(0)
        }
    }

    private fun selfTest() {
        result.text = try {
            val ks = store()
            val device = savedId()
            check(device != null && ks.containsAlias(SIGN_ALIAS) &&
                ks.containsAlias(ECDH_ALIAS)) {
                "Local keys missing"
            }
            val signingPublic = ks.getCertificate(SIGN_ALIAS).publicKey as ECPublicKey
            val ecdhPublic = ks.getCertificate(ECDH_ALIAS).publicKey as ECPublicKey
            val signingPrivate = ks.getKey(SIGN_ALIAS, null) as PrivateKey
            val ecdhPrivate = ks.getKey(ECDH_ALIAS, null) as PrivateKey
            val signingHash = fingerprint(signingPublic)
            val ecdhHash = fingerprint(ecdhPublic)

            val issued = System.currentTimeMillis()
            val expires = issued + OfflineProofPolicy.MAX_TTL_MS
            val challenge = UUID.randomUUID().toString()
            val payload = OfflineProofPolicy.canonicalPayload(
                device, challenge, issued, expires, signingHash, ecdhHash
            ) ?: error("Invalid local proof fields")
            check(OfflineProofPolicy.inspectSample(
                device, challenge, issued, expires, System.currentTimeMillis(),
                signingHash, ecdhHash, payload
            ) == FreshPrepDecision.LOCAL_CRYPTO_SELF_TEST_ONLY_NOT_TRUSTED)
            val bytes = payload.toByteArray(StandardCharsets.UTF_8)
            val sig = Signature.getInstance("SHA256withECDSA").run {
                initSign(signingPrivate)
                update(bytes)
                sign()
            }
            val valid = Signature.getInstance("SHA256withECDSA").run {
                initVerify(signingPublic)
                update(bytes)
                verify(sig)
            }
            val tampered = Signature.getInstance("SHA256withECDSA").run {
                initVerify(signingPublic)
                update((payload + "\nUNTRUSTED").toByteArray(StandardCharsets.UTF_8))
                verify(sig)
            }
            check(valid && !tampered) { "P-256 signing check failed" }
            check(runECDH(ecdhPrivate, ecdhPublic)) {
                "P-256 ECDH agreement failed"
            }
            "LOCAL_CRYPTO_SELF_TEST_PASS\n" +
                "ECDSA P-256 sign/verify: PASS\n" +
                "Tampered signature verification: DENIED\n" +
                "ECDH P-256 shared-secret agreement: PASS\n" +
                "Test device ID: $device\n" +
                "Signing public fingerprint (SHA-256):\n$signingHash\n" +
                "ECDH public fingerprint (SHA-256):\n$ecdhHash\n" +
                "serverApproved: false\n" +
                "trustedDevice: false\n" +
                "e2eeV2Ready: false\n" +
                "NO BACKEND OR SECOND PHONE TEST PERFORMED"
        } catch (_: Exception) {
            "LOCAL_CRYPTO_SELF_TEST_NOT_PASSED. " +
                "No keys, device approvals or server data changed."
        }
    }
}
